package qti_kernel_headers

import (
	"android/soong/android"
	"android/soong/cc"
	"fmt"
	"path/filepath"
)

func init() {
	// Register our own module type
	android.RegisterModuleType("qti_kernel_headers", qtiKernelHeadersFactory)
	android.RegisterModuleType("qti_techpack_headers", qtiTechpackHeadersFactory)
}

type versionedLibsProps struct {
	Export_header_lib_headers []string
	Header_libs               []string
}

type techpackProps struct {
	// Directory name under common-headers/techpack-headers/ that provides the real headers
	Techpack *string
}

// addVersionedLib makes the calling module re-export "<module name>_<version>"
// (generated by cp_headers.py).
func addVersionedLib(ctx android.LoadHookContext, version string) {
	name := fmt.Sprintf("%s_%s", ctx.ModuleName(), version)
	ctx.AppendProperties(&versionedLibsProps{
		[]string{name},
		[]string{name},
	})
}

// Core: always re-exports qti_kernel_headers_<version> (from common-headers/kernel-headers)
func qtiKernelHeadersFactory() android.Module {
	module := cc.LibraryHeaderFactory()
	android.AddLoadHook(module, func(ctx android.LoadHookContext) {
		config := ctx.Config().VendorConfig("qti_kernel_headers")
		if config.IsSet("version") {
			addVersionedLib(ctx, config.String("version"))
		}
	})
	return module
}

// Techpack: stays dummy unless common-headers/techpack-headers/<techpack> has
// headers for the selected version, then re-exports <module name>_<version>.
func qtiTechpackHeadersFactory() android.Module {
	props := &techpackProps{}
	module := cc.LibraryHeaderFactory()
	module.AddProperties(props)
	android.AddLoadHook(module, func(ctx android.LoadHookContext) {
		config := ctx.Config().VendorConfig("qti_kernel_headers")
		if !config.IsSet("version") || props.Techpack == nil || *props.Techpack == "" {
			return
		}
		version := config.String("version")

		dir := filepath.Join(ctx.ModuleDir(), "..", "msm-"+version,
			"common-headers", "techpack-headers", *props.Techpack)
		matches, err := ctx.GlobWithDeps(filepath.Join(dir, "*"), nil)
		if err != nil || len(matches) == 0 {
			// No real headers for this version, stay a dummy
			return
		}
		addVersionedLib(ctx, version)
	})
	return module
}
